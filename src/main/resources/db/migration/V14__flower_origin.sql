-- ============================================================================
-- V14：鲜花产地与地理网络（地图功能的底座）
--   flower_origin    一张表装下三类地图节点：kind = origin 直采产地 / hub 分拨中心 / store 自提门店
--                    坐标为 GCJ-02（与高德底图同系），海拔与主营品种用于产地卡片的品质叙事
--   product.origin_id 商品主产地，一物一地；缺省按分类回填，商品详情页据此讲「这束花来自哪里」
-- 说明：销量地图的城市聚合走地址文本 + 内置城市质心字典，不额外加列，避免为一个视图改动交易主链路的表
-- ============================================================================

CREATE TABLE IF NOT EXISTS flower_origin (
    id         uuid          NOT NULL,
    name       varchar(60)   NOT NULL,
    kind       varchar(16)   NOT NULL DEFAULT 'origin',
    province   varchar(40),
    city       varchar(40),
    adcode     varchar(12),
    lng        numeric(9, 6) NOT NULL,
    lat        numeric(9, 6) NOT NULL,
    altitude   integer,
    flowers    varchar(255),
    feature    varchar(120),
    story      varchar(500),
    season     varchar(60),
    sort_order integer       NOT NULL DEFAULT 0,
    is_active  boolean       NOT NULL DEFAULT true,
    created_at timestamp     NOT NULL,
    updated_at timestamp     NOT NULL,
    CONSTRAINT flower_origin_pkey PRIMARY KEY (id),
    CONSTRAINT ck_flower_origin_kind CHECK (kind IN ('origin', 'hub', 'store'))
);

CREATE INDEX IF NOT EXISTS idx_flower_origin_kind ON flower_origin (kind, sort_order);

